"""PDF bytes for report cards and fee receipts. No card data is accepted."""

from __future__ import annotations

import io

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas


def _canvas(title: str) -> tuple[canvas.Canvas, io.BytesIO]:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    pdf.setTitle(title)
    return pdf, buffer


def report_card_pdf(data: dict) -> bytes:
    pdf, buffer = _canvas("EduNexus report card")
    y = 800
    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(48, y, "EduNexus Report Card")
    pdf.setFont("Helvetica", 11)
    y -= 28
    lines = [
        f"School: {data.get('school_name', '')}",
        f"Student: {data.get('student_name', '')}",
        f"Admission: {data.get('admission_no', '')}",
        f"Class: {data.get('class_name', '')} {data.get('section', '')}",
        f"Exam: {data.get('exam_name', '')} ({data.get('exam_status', '')})",
        f"Result: {data.get('result', '')}",
        f"Average: {data.get('average_percentage', '')}",
        f"Overall grade: {data.get('overall_grade', '')}",
    ]
    for line in lines:
        pdf.drawString(48, y, str(line)[:110])
        y -= 16
    y -= 8
    pdf.setFont("Helvetica-Bold", 11)
    pdf.drawString(48, y, "Subject")
    pdf.drawString(260, y, "Marks")
    pdf.drawString(360, y, "Grade")
    pdf.drawString(430, y, "Pass")
    pdf.setFont("Helvetica", 10)
    y -= 16
    for subject in data.get("subjects", []):
        marks = "Absent" if subject.get("absent") else f"{subject.get('marks_obtained')} / {subject.get('max_marks')}"
        pdf.drawString(48, y, str(subject.get("subject_name", ""))[:32])
        pdf.drawString(260, y, marks)
        pdf.drawString(360, y, str(subject.get("grade") or "-"))
        pdf.drawString(430, y, "-" if subject.get("passed") is None else ("Yes" if subject.get("passed") else "No"))
        y -= 14
        if y < 60:
            pdf.showPage()
            y = 800
    pdf.setFont("Helvetica-Oblique", 8)
    pdf.drawString(48, 40, "Generated by EduNexus. Grades follow the published scale. This is not a certificate of character.")
    pdf.save()
    return buffer.getvalue()


def fee_receipt_pdf(data: dict) -> bytes:
    pdf, buffer = _canvas("EduNexus fee receipt")
    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(48, 800, "EduNexus Fee Receipt")
    pdf.setFont("Helvetica", 11)
    y = 760
    for line in (
        f"Receipt for invoice {data.get('invoice_no', '')}",
        f"School: {data.get('school_name', '')}",
        f"Student: {data.get('student_name', '')} ({data.get('admission_no', '')})",
        f"Description: {data.get('description', '')}",
        f"Amount due: {data.get('amount_due', '')}",
        f"Concession: {data.get('concession', '')}",
        f"Amount paid: {data.get('amount_paid', '')}",
        f"Payment id: {data.get('payment_id', '')}",
        f"Order id: {data.get('order_id', '')}",
        f"Gateway: {data.get('gateway', '')}",
        f"Status: {data.get('status', '')}",
        f"Paid at: {data.get('paid_at', '')}",
    ):
        pdf.drawString(48, y, str(line)[:110])
        y -= 18
    pdf.setFont("Helvetica-Oblique", 8)
    pdf.drawString(48, 40, "Card numbers are not stored. This receipt is issued only after payment verification.")
    pdf.save()
    return buffer.getvalue()
